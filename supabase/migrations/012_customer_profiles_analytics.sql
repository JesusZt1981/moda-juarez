create table if not exists public.store_analytics_events (
  id bigint generated by default as identity primary key,
  event_name text not null,
  visitor_id text not null,
  session_id text,
  user_id uuid references auth.users(id) on delete set null,
  product_id bigint references public.shop_products(id) on delete set null,
  product_sku text,
  occurred_at timestamptz not null default now(),
  event_date date not null default (timezone('America/Ciudad_Juarez',now()))::date,
  metadata jsonb not null default '{}'::jsonb,
  constraint store_analytics_event_name_check check (event_name in ('store_visit','product_view','add_to_cart','begin_checkout')),
  constraint store_analytics_visitor_check check (char_length(visitor_id) between 8 and 100)
);
create index if not exists store_analytics_events_date_idx on public.store_analytics_events(event_date desc);
create index if not exists store_analytics_events_user_idx on public.store_analytics_events(user_id,occurred_at desc);
create index if not exists store_analytics_events_product_idx on public.store_analytics_events(product_sku,occurred_at desc);
create unique index if not exists store_visit_user_daily_uq on public.store_analytics_events(event_date,user_id,event_name) where event_name='store_visit' and user_id is not null;
create unique index if not exists store_visit_visitor_daily_uq on public.store_analytics_events(event_date,visitor_id,event_name) where event_name='store_visit' and user_id is null;
create unique index if not exists product_view_user_daily_uq on public.store_analytics_events(event_date,user_id,product_sku,event_name) where event_name='product_view' and user_id is not null and product_sku is not null;
create unique index if not exists product_view_visitor_daily_uq on public.store_analytics_events(event_date,visitor_id,product_sku,event_name) where event_name='product_view' and user_id is null and product_sku is not null;

create table if not exists public.product_likes (
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references public.shop_products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(user_id,product_id)
);
create index if not exists product_likes_product_idx on public.product_likes(product_id,created_at desc);

create table if not exists public.marketing_consent_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  consent boolean not null,
  source text not null default 'profile',
  created_at timestamptz not null default now()
);
create index if not exists marketing_consent_log_user_idx on public.marketing_consent_log(user_id,created_at desc);

create table if not exists public.marketing_subscribers (
  id bigint generated by default as identity primary key,
  email text not null,
  email_normalized text generated always as (lower(btrim(email))) stored,
  active boolean not null default true,
  adult_confirmed boolean not null default false,
  source text not null default 'newsletter',
  consent_at timestamptz not null default now(),
  unsubscribed_at timestamptz,
  unique(email_normalized)
);

