create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
declare v_age smallint; v_marketing boolean:=false; v_first text; v_last text; v_phone text; v_provider text;
begin
  if coalesce(new.raw_user_meta_data->>'age','') ~ '^\d{1,3}$' then v_age:=(new.raw_user_meta_data->>'age')::smallint; if v_age<13 or v_age>80 then v_age:=null; end if; end if;
  v_first:=coalesce(nullif(new.raw_user_meta_data->>'first_name',''),nullif(new.raw_user_meta_data->>'given_name',''));
  v_last:=coalesce(nullif(new.raw_user_meta_data->>'last_name',''),nullif(new.raw_user_meta_data->>'family_name',''));
  v_phone:=nullif(new.raw_user_meta_data->>'phone','');
  v_provider:=coalesce(nullif(new.raw_app_meta_data->>'provider',''),'email');
  v_marketing:=lower(coalesce(new.raw_user_meta_data->>'marketing_consent','false')) in ('true','1','yes','si','sí') and coalesce(v_age,18)>=18;
  insert into public.profiles(id,email,contact_email,role,first_name,last_name,phone,age,auth_provider,marketing_consent,marketing_consent_at,profile_completed_at,last_seen,updated_at)
  values(new.id,new.email,new.email,'customer',v_first,v_last,v_phone,v_age,v_provider,v_marketing,case when v_marketing then now() end,case when v_first is not null and v_last is not null and new.email is not null and v_phone is not null and v_age is not null then now() end,now(),now())
  on conflict(id) do update set email=excluded.email,contact_email=coalesce(public.profiles.contact_email,excluded.contact_email),auth_provider=coalesce(nullif(public.profiles.auth_provider,''),excluded.auth_provider),first_name=coalesce(public.profiles.first_name,excluded.first_name),last_name=coalesce(public.profiles.last_name,excluded.last_name),updated_at=now();
  return new;
end; $$;

create or replace function public.record_store_event(p_event_name text,p_visitor_id text,p_session_id text default null,p_product_sku text default null,p_metadata jsonb default '{}'::jsonb)
returns boolean language plpgsql security definer set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_product_id bigint; v_metadata jsonb:=coalesce(p_metadata,'{}'::jsonb);
begin
  if p_event_name not in ('store_visit','product_view','add_to_cart','begin_checkout') then raise exception 'Evento no permitido'; end if;
  if p_visitor_id is null or char_length(p_visitor_id)<8 or char_length(p_visitor_id)>100 then raise exception 'Visitante inválido'; end if;
  if pg_column_size(v_metadata)>8192 then raise exception 'Metadata demasiado grande'; end if;
  if p_product_sku is not null then select id into v_product_id from public.shop_products where sku=p_product_sku limit 1; end if;
  begin insert into public.store_analytics_events(event_name,visitor_id,session_id,user_id,product_id,product_sku,metadata) values(p_event_name,p_visitor_id,p_session_id,v_uid,v_product_id,p_product_sku,v_metadata);
  exception when unique_violation then if v_uid is not null then update public.profiles set last_seen=now(),updated_at=now() where id=v_uid; end if; return false; end;
  if v_uid is not null then update public.profiles set last_seen=now(),updated_at=now() where id=v_uid; end if; return true;
end; $$;

create or replace function public.set_my_profile(p_first_name text,p_last_name text,p_contact_email text,p_phone text,p_age smallint,p_marketing_consent boolean default false)
returns public.profiles language plpgsql security definer set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_previous boolean; v_effective boolean; v_row public.profiles;
begin
  if v_uid is null then raise exception 'Debes iniciar sesión'; end if;
  if nullif(btrim(p_first_name),'') is null or char_length(btrim(p_first_name))>80 then raise exception 'Nombre inválido'; end if;
  if nullif(btrim(p_last_name),'') is null or char_length(btrim(p_last_name))>120 then raise exception 'Apellido inválido'; end if;
  if p_contact_email is null or p_contact_email !~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$' then raise exception 'Correo inválido'; end if;
  if nullif(btrim(p_phone),'') is null or char_length(btrim(p_phone))>30 then raise exception 'Teléfono inválido'; end if;
  if p_age is null or p_age<13 or p_age>80 then raise exception 'Edad fuera de rango'; end if;
  select marketing_consent into v_previous from public.profiles where id=v_uid; v_effective:=coalesce(p_marketing_consent,false) and p_age>=18;
  update public.profiles set first_name=btrim(p_first_name),last_name=btrim(p_last_name),contact_email=lower(btrim(p_contact_email)),phone=btrim(p_phone),age=p_age,marketing_consent=v_effective,marketing_consent_at=case when v_effective then coalesce(marketing_consent_at,now()) end,profile_completed_at=coalesce(profile_completed_at,now()),last_seen=now(),updated_at=now() where id=v_uid returning * into v_row;
  if v_previous is distinct from v_effective then insert into public.marketing_consent_log(user_id,consent,source) values(v_uid,v_effective,'profile'); end if; return v_row;
end; $$;

create or replace function public.toggle_product_like(p_product_sku text,p_like boolean)
returns boolean language plpgsql security definer set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_product_id bigint;
begin
  if v_uid is null then raise exception 'Debes iniciar sesión'; end if;
  select id into v_product_id from public.shop_products where sku=p_product_sku and active=true limit 1;
  if v_product_id is null then raise exception 'Producto no encontrado'; end if;
  if p_like then insert into public.product_likes(user_id,product_id) values(v_uid,v_product_id) on conflict do nothing; return true; end if;
  delete from public.product_likes where user_id=v_uid and product_id=v_product_id; return false;
end; $$;

create or replace function public.subscribe_marketing(p_email text,p_adult_confirmed boolean,p_source text default 'newsletter')
returns boolean language plpgsql security definer set search_path=public as $$
begin
  if p_email is null or p_email !~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$' then raise exception 'Correo inválido'; end if;
  if coalesce(p_adult_confirmed,false) is not true then raise exception 'La suscripción de ofertas requiere confirmar mayoría de edad'; end if;
  insert into public.marketing_subscribers(email,active,adult_confirmed,source,consent_at,unsubscribed_at) values(lower(btrim(p_email)),true,true,coalesce(nullif(p_source,''),'newsletter'),now(),null)
  on conflict(email_normalized) do update set email=excluded.email,active=true,adult_confirmed=true,source=excluded.source,consent_at=now(),unsubscribed_at=null; return true;
end; $$;

